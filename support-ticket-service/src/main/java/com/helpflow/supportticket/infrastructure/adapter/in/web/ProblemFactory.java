package com.helpflow.supportticket.infrastructure.adapter.in.web;

import java.net.URI;
import java.time.Instant;
import java.util.Arrays;
import java.util.Locale;
import org.slf4j.MDC;
import org.springframework.context.MessageSource;
import org.springframework.http.HttpStatus;
import org.springframework.http.ProblemDetail;
import org.springframework.stereotype.Component;

/**
 * Builds RFC 7807 problem documents with localized title/detail, a timestamp and the trace id of the
 * request. Message keys are {@code problem.<code>.title} and {@code problem.<code>.detail}.
 */
@Component
public class ProblemFactory {

    static final String TYPE_PREFIX = "urn:helpflow:problem:";

    private final MessageSource messages;

    ProblemFactory(MessageSource messages) {
        this.messages = messages;
    }

    public ProblemDetail create(HttpStatus status, String code, Locale locale, String instance, Object... args) {
        ProblemDetail problem = ProblemDetail.forStatusAndDetail(status,
                messages.getMessage("problem." + code + ".detail", asText(args), locale));
        problem.setType(URI.create(TYPE_PREFIX + code));
        problem.setTitle(messages.getMessage("problem." + code + ".title", null, locale));
        decorate(problem, instance);
        return problem;
    }

    /**
     * MessageFormat would render ids as "999,999" (en) or "999.999" (es); identifiers must stay as typed.
     */
    private static Object[] asText(Object[] args) {
        return args == null ? null : Arrays.stream(args).map(String::valueOf).toArray();
    }

    /**
     * Adds the common members to problems generated by Spring MVC itself (404, 405, 415, ...).
     */
    public void decorate(ProblemDetail problem, String instance) {
        if (problem.getInstance() == null && instance != null) {
            problem.setInstance(URI.create(instance));
        }
        problem.setProperty("timestamp", Instant.now());
        problem.setProperty("traceId", MDC.get(TraceIdFilter.MDC_KEY));
    }

    public String message(String key, Locale locale, Object... args) {
        return messages.getMessage(key, args, locale);
    }
}

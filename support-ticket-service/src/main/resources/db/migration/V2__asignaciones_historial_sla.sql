-- Assignments, audit history and SLA configuration.

CREATE TABLE ticket_assignments (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id     BIGINT       NOT NULL,
  technician_id BIGINT       NOT NULL,
  source        VARCHAR(10)  NOT NULL,
  estimated_hours INTEGER,
  availability  VARCHAR(10),
  within_sla    BOOLEAN,
  assigned_by   VARCHAR(254) NOT NULL,
  assigned_at   TIMESTAMPTZ  NOT NULL,
  active        BOOLEAN      NOT NULL,
  CONSTRAINT fk_assignments_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id),
  CONSTRAINT fk_assignments_technician FOREIGN KEY (technician_id) REFERENCES technicians (id),
  CONSTRAINT ck_assignments_source CHECK (source IN ('DISPATCH', 'RULES', 'MANUAL')),
  CONSTRAINT ck_assignments_availability CHECK (availability IS NULL OR availability IN ('ALTA', 'MEDIA', 'BAJA'))
);

-- A ticket has at most one active assignment.
CREATE UNIQUE INDEX uq_assignments_active_ticket ON ticket_assignments (ticket_id) WHERE active;
CREATE INDEX ix_assignments_ticket ON ticket_assignments (ticket_id);

CREATE TABLE ticket_history (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id    BIGINT        NOT NULL,
  action       VARCHAR(20)   NOT NULL,
  from_status  VARCHAR(15),
  to_status    VARCHAR(15),
  performed_by VARCHAR(254)  NOT NULL,
  observations VARCHAR(1000),
  occurred_at  TIMESTAMPTZ   NOT NULL,
  CONSTRAINT fk_history_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id),
  CONSTRAINT ck_history_action CHECK (action IN
    ('CREATED', 'ASSIGNED', 'REASSIGNED', 'ASSIGNMENT_PENDING', 'STATUS_CHANGED', 'ESCALATED', 'SLA_BREACHED'))
);

CREATE INDEX ix_history_ticket ON ticket_history (ticket_id, occurred_at);

CREATE TABLE sla_policies (
  priority                     VARCHAR(10) PRIMARY KEY,
  resolution_hours             INTEGER     NOT NULL,
  escalation_threshold_percent INTEGER     NOT NULL,
  CONSTRAINT ck_sla_priority CHECK (priority IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
  CONSTRAINT ck_sla_hours CHECK (resolution_hours >= 1),
  CONSTRAINT ck_sla_threshold CHECK (escalation_threshold_percent BETWEEN 1 AND 99)
);


-- Core schema: users, technicians and tickets.

CREATE SEQUENCE technician_code_seq START WITH 16 INCREMENT BY 1;

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document      VARCHAR(30)  NOT NULL,
  full_name     VARCHAR(120) NOT NULL,
  email         VARCHAR(254) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  site          VARCHAR(60)  NOT NULL,
  area          VARCHAR(60)  NOT NULL,
  status        VARCHAR(10)  NOT NULL,
  role          VARCHAR(20)  NOT NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_document UNIQUE (document),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT ck_users_status CHECK (status IN ('ACTIVO', 'INACTIVO')),
  CONSTRAINT ck_users_role CHECK (role IN ('ROLE_USUARIO', 'ROLE_TECNICO', 'ROLE_ADMIN'))
);

CREATE TABLE technicians (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code               VARCHAR(20)  NOT NULL,
  user_id            BIGINT,
  full_name          VARCHAR(120) NOT NULL,
  specialty          VARCHAR(20)  NOT NULL,
  site               VARCHAR(60)  NOT NULL,
  max_active_tickets INTEGER      NOT NULL,
  status             VARCHAR(10)  NOT NULL,
  CONSTRAINT uq_technicians_code UNIQUE (code),
  CONSTRAINT uq_technicians_user UNIQUE (user_id),
  CONSTRAINT fk_technicians_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT ck_technicians_specialty CHECK (specialty IN ('HARDWARE', 'SOFTWARE', 'RED', 'ACCESOS', 'OTRO')),
  CONSTRAINT ck_technicians_capacity CHECK (max_active_tickets >= 1),
  CONSTRAINT ck_technicians_status CHECK (status IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE tickets (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id           BIGINT        NOT NULL,
  title                  VARCHAR(150)  NOT NULL,
  description            VARCHAR(4000) NOT NULL,
  category               VARCHAR(20)   NOT NULL,
  priority               VARCHAR(10)   NOT NULL,
  site                   VARCHAR(60)   NOT NULL,
  affected_asset         VARCHAR(120)  NOT NULL,
  status                 VARCHAR(15)   NOT NULL,
  created_at             TIMESTAMPTZ   NOT NULL,
  sla_due_at             TIMESTAMPTZ   NOT NULL,
  assigned_technician_id BIGINT,
  first_response_at      TIMESTAMPTZ,
  resolved_at            TIMESTAMPTZ,
  escalated              BOOLEAN       NOT NULL DEFAULT FALSE,
  escalated_at           TIMESTAMPTZ,
  sla_breached           BOOLEAN       NOT NULL DEFAULT FALSE,
  version                BIGINT        NOT NULL DEFAULT 0,
  CONSTRAINT fk_tickets_requester FOREIGN KEY (requester_id) REFERENCES users (id),
  CONSTRAINT fk_tickets_technician FOREIGN KEY (assigned_technician_id) REFERENCES technicians (id),
  CONSTRAINT ck_tickets_category CHECK (category IN ('HARDWARE', 'SOFTWARE', 'RED', 'ACCESOS', 'OTRO')),
  CONSTRAINT ck_tickets_priority CHECK (priority IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
  CONSTRAINT ck_tickets_status CHECK (status IN ('ABIERTO', 'ASIGNADO', 'EN_PROGRESO', 'RESUELTO', 'CERRADO', 'CANCELADO')),
  CONSTRAINT ck_tickets_sla CHECK (sla_due_at > created_at)
);

CREATE INDEX ix_tickets_requester ON tickets (requester_id);
CREATE INDEX ix_tickets_technician_status ON tickets (assigned_technician_id, status);
CREATE INDEX ix_tickets_status ON tickets (status);
CREATE INDEX ix_tickets_sla_running ON tickets (sla_due_at) WHERE status IN ('ABIERTO', 'ASIGNADO', 'EN_PROGRESO');
